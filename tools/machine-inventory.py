#!/usr/bin/env python3
"""Machine inventory + loot census across all pack jars (Minebricks).

Outputs (staged in friend-pack/, not shipped):
  MACHINE-INVENTORY.md  - per-mod machine blocks (lang-derived) + recipe-type census
  LOOT-CENSUS.md        - per-mod loot table counts by family
Provenance rule: every name/ID comes from the jars on disk. Zero guessed IDs.
"""
import glob, json, os, re, zipfile
from collections import defaultdict

JARS = "/home/z/my-project/scratch/jars"
PACK = "/home/z/my-project/scratch/packwiz-build/friend-pack"

# Machine-ish keywords matched against the en_us display NAME (not the id),
# so "precision_assembler" and "Precision Assembler" both hit.
KW = re.compile(
    r"\b(machine|assembler|assembly|furnace|electrolyzer|electrolyser|centrifuge|"
    r"reactor|crusher|grinder|mill|pulverizer|macerator|shredder|granulator|press|"
    r"smelter|foundry|kiln|oven|heater|freezer|condenser|crystallizer|distill|"
    r"extractor|processor|generator|turbine|pump|drill|refinery|refiner|caster|"
    r"casting|basin|crucible|chamber|mixer|lathe|infuser|compressor|washer|"
    r"separator|sawmill|excavator|quarry|collector|sealer|terraformer|pad|"
    r"station|loader|monitor|scanner|intake|hatch|vent)\b",
    re.I,
)
# Exclude obvious false positives by name
EXC = re.compile(r"(strap|station wagon|artwork|music|painting|sign|statue)", re.I)

rec_types = defaultdict(lambda: defaultdict(int))   # ns -> type -> count
machines  = defaultdict(list)                        # mod filename -> [(id, name)]
loot      = defaultdict(lambda: defaultdict(int))   # mod filename -> family -> count
mods_seen = []

def family_of(path):
    p = path.lower()
    if "chest" in p: return "chests"
    if "entity" in p or "entities" in p: return "entities"
    if "blocks" in p or "/block" in p: return "blocks"
    if "fishing" in p: return "fishing"
    if "gift" in p: return "gifts"
    if "shearing" in p: return "shearing"
    if "gameplay" in p: return "gameplay"
    if "dispenser" in p: return "dispenser-registry"
    return "other"

for jar in sorted(glob.glob(os.path.join(JARS, "*.jar"))):
    fname = os.path.basename(jar)
    z = zipfile.ZipFile(jar)
    langs, recipes, loots, mbd = [], [], [], []
    for n in z.namelist():
        if n.endswith("lang/en_us.json"): langs.append(n)
        elif re.search(r"data/[^/]+/recipe(s)?/.+\.json$", n): recipes.append(n)
        elif re.search(r"data/[^/]+/loot_tables?/.+\.json$", n): loots.append(n)
        elif "mbd2" in n and n.endswith(".json"): mbd.append(n)
    if not (langs or recipes or loots or mbd):
        continue
    mods_seen.append(fname)

    for lang in langs:
        ns = lang.split("/")[1]
        try:
            data = json.loads(z.read(lang))
        except Exception:
            continue
        for k, v in data.items():
            if not k.startswith("block.") or not isinstance(v, str):
                continue
            if KW.search(v) and not EXC.search(v):
                machines[fname].append((k[len("block."):], v))

    for r in recipes:
        m = re.match(r"data/([^/]+)/recipe(s)?/", r)
        if not m:
            continue
        ns = m.group(1)
        try:
            t = json.loads(z.read(r)).get("type", "?")
        except Exception:
            t = "<unparsable>"
        rec_types[ns][t] += 1

    loot[fname] = defaultdict(int)
    for l in loots:
        ns = l.split("/")[1]
        rest = re.sub(r"^data/[^/]+/loot_tables?/", "", l)
        parts = rest.split("/")
        fam = parts[0] if len(parts) > 1 else "root"
        loot[fname][fam] += 1

    if mbd:
        print(f"[info] {fname}: {len(mbd)} mbd2 definition jsons inside jar")

z.close()

# ---- write MACHINE-INVENTORY.md -------------------------------------------
def mod_label(fname):
    return fname.replace(".jar", "")

inv = ["# MACHINE-INVENTORY — every machine block in the pack, jar-derived",
       "",
       "Generated by scripts/machine-inventory.py against all 58 jars on disk",
       "(sha512-verified pulls from pack.toml). Provenance: assets/*/lang/en_us.json",
       "block names + data/*/recipe*/ JSON types. Nothing guessed.",
       "",
       "This file is the evidence base for the machine question and the AR3",
       "complement check. It is staged next to NEXT-UP.md, not shipped.",
       ""]

for fname in mods_seen:
    ms = sorted(set(machines.get(fname, [])))
    if not ms:
        continue
    inv.append(f"## {mod_label(fname)}")
    inv.append("")
    for _id, name in ms:
        inv.append(f"- {name}  `{_id}`")
    inv.append("")

inv.append("## Recipe-type census (data/*/recipe*/ JSONs)")
inv.append("")
for ns in sorted(rec_types):
    total = sum(rec_types[ns].values())
    if total == 0:
        continue
    inv.append(f"### {ns} ({total} recipe jsons)")
    for t in sorted(rec_types[ns]):
        inv.append(f"- {rec_types[ns][t]}x  `{t}`")
    inv.append("")

open(os.path.join(PACK, "MACHINE-INVENTORY.md"), "w").write("\n".join(inv) + "\n")

# ---- write LOOT-CENSUS.md ---------------------------------------------------
lc = ["# LOOT-CENSUS — loot tables shipped per mod, jar-derived",
      "",
      "Same scan as MACHINE-INVENTORY. Path families under data/<ns>/loot_table/.",
      "This is artifact zero of the loot pass: what exists before we decide",
      "keep/kill. Runtime tables (none yet — no LootJS) would add on top.",
      ""]
for fname in sorted(loot):
    fams = loot[fname]
    total = sum(fams.values())
    if total == 0:
        continue
    parts = ", ".join(f"{k} {v}" for k, v in sorted(fams.items(), key=lambda x: -x[1]))
    lc.append(f"- **{mod_label(fname)}** — {total} tables ({parts})")
lc.append("")
open(os.path.join(PACK, "LOOT-CENSUS.md"), "w").write("\n".join(lc) + "\n")

# ---- stdout digest ----------------------------------------------------------
print(f"mods scanned: {len(mods_seen)}")
print(f"machine-name hits: {sum(len(v) for v in machines.values())} across {len(machines)} mods")
print(f"recipe namespaces: {len(rec_types)}")
print(f"loot mods: {len(loot)}")
ar3 = [m for f, ms in machines.items() if "adv_rocketry" in f for m in ms]
print(f"AR3 machine-name hits: {len(ar3)}")
for _id, name in sorted(ar3):
    print("  AR3:", name, "|", _id)
